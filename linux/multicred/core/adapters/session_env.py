"""The graphical session environment (the Linux counterpart of `launchctl setenv`).

Two places, kept together:
- `systemctl --user set-environment/unset-environment`: the user manager, read by
  services and D-Bus-activated apps started from now on;
- `~/.config/environment.d/90-multicred.conf`: read by systemd at the next
  login, so GNOME Shell, COSMIC and every app they launch get the variable.

Apps opened before a switch keep their environment, as on macOS.
"""

from __future__ import annotations

import re

from ..runner import CommandRequest, run_checked
from ..storage import AtomicFileWriter, read_bytes, restore_file

SYSTEMCTL = "/usr/bin/systemctl"
ENVIRONMENT_D_FILE = ".config/environment.d/90-multicred.conf"
_HEADER = "# Generated by MultiCred. Do not edit.\n"

# environment.d expands $VAR even inside quotes, treats backslashes and double
# quotes specially, and strips a quote or space at either end. An apostrophe in
# the middle round-trips (checked against the real generator in the tests).
_UNSAFE_FOR_ENVIRONMENT_D = re.compile(r"[$\\\"`]|^['\s]|['\s]$")


def representable(value: str) -> bool:
    """Whether environment.d can hold `value` and read it back exactly. When it cannot,
    only the running user manager gets the value: graphical apps go back to the
    default at the next login."""
    return bool(value) and not _UNSAFE_FOR_ENVIRONMENT_D.search(value)


def environment_d_line(name: str, value: str) -> str | None:
    """`NAME=value` as environment.d reads it back exactly, or None when it cannot."""
    if not representable(value):
        return None
    return f"{name}={value}"


def _unescape_ansi_c(text: str) -> str:
    out, i = [], 0
    simple = {"n": "\n", "t": "\t", "r": "\r", "\\": "\\", "'": "'", '"': '"', "a": "\a", "b": "\b",
              "e": "\x1b", "f": "\f", "v": "\v"}
    while i < len(text):
        ch = text[i]
        if ch == "\\" and i + 1 < len(text):
            nxt = text[i + 1]
            if nxt in simple:
                out.append(simple[nxt])
                i += 2
                continue
            if nxt == "x":
                digits = re.match(r"[0-9A-Fa-f]{1,2}", text[i + 2:])
                if digits:
                    out.append(chr(int(digits.group(), 16)))
                    i += 2 + len(digits.group())
                    continue
        out.append(ch)
        i += 1
    return "".join(out)


def _decode_value(raw: str) -> str:
    if raw.startswith("$'") and raw.endswith("'") and len(raw) >= 3:
        return _unescape_ansi_c(raw[2:-1])
    if raw.startswith('"') and raw.endswith('"') and len(raw) >= 2:
        return re.sub(r'\\([\\"$`])', r"\1", raw[1:-1])
    if raw.startswith("'") and raw.endswith("'") and len(raw) >= 2:
        return raw[1:-1]
    return raw


def parse_show_environment(text: str) -> dict[str, str]:
    """Parses `systemctl --user show-environment` (values may be shell-quoted)."""
    values = {}
    for line in text.splitlines():
        if "=" not in line:
            continue
        name, raw = line.split("=", 1)
        values[name] = _decode_value(raw)
    return values


class SessionEnvironment:
    def __init__(self, environment, base_environment: dict[str, str]):
        self.environment = environment
        self.runner = environment.runner
        self.base_environment = dict(base_environment)
        self.file = environment.home / ENVIRONMENT_D_FILE

    def _systemctl(self, *arguments: str):
        return run_checked(self.runner, CommandRequest(SYSTEMCTL, ["--user", *arguments], self.base_environment,
                                                       timeout=10))

    def get(self, name: str) -> str | None:
        """None when the variable is not set in the user manager."""
        return parse_show_environment(self._systemctl("show-environment").stdout).get(name)

    def _set_manager(self, name: str, value: str | None) -> None:
        if value is None:
            self._systemctl("unset-environment", name)
        else:
            self._systemctl("set-environment", f"{name}={value}")

    def _file_bytes(self, name: str, value: str | None) -> bytes | None:
        line = environment_d_line(name, value) if value is not None else None
        return None if line is None else (_HEADER + line + "\n").encode()

    def apply(self, name: str, value: str | None):
        """Sets (or, for None, unsets) the variable in both places. Returns the undo."""
        previous = self.get(name)
        previous_file = read_bytes(self.file)
        wanted_file = self._file_bytes(name, value)
        if previous == value and previous_file == wanted_file:
            return lambda: None

        if wanted_file != previous_file:
            if wanted_file is None:
                restore_file(None, self.file)
            else:
                AtomicFileWriter.write(wanted_file, self.file, permissions=0o644)
        if previous != value:
            try:
                self._set_manager(name, value)
            except Exception:
                restore_file(previous_file, self.file)
                raise

        def undo():
            restore_file(previous_file, self.file)
            if previous != value:
                self._set_manager(name, previous)

        return undo
