"""env.sh (bash, zsh) and env.fish.

Only variable names (validated), canonical paths (quoted) and UUIDs reach these
files; secret values never do. How the shell gets a value depends on the platform
(`secret_reader_for`): on the desktop it asks the Secret Service through
`secret-tool` when the shell sources the file; on Termux, which has no Secret
Service, it reads the key's 0600 file with shell builtins only (no program runs
at each prompt).
"""

from __future__ import annotations

from dataclasses import dataclass, field

from ..engine.types import ClaudeTarget
from ..file_secrets import SECRETS_DIRECTORY_NAME
from ..quoting import fish_single_quoted, single_quoted
from ..secrets import API_KEY_SERVICE, validate_account

SECRET_TOOL = "/usr/bin/secret-tool"
# Same convention as the shell hooks (rendering/hooks.py): relative to $HOME.
SECRETS_DIRECTORY_EXPRESSION = f"$HOME/.config/multicred/{SECRETS_DIRECTORY_NAME}"


@dataclass(frozen=True)
class APIKeyExport:
    env_var: str
    secret_account: str


@dataclass
class ShellEnvironment:
    """The environment a profile wants in the user's shells."""

    generation: int
    # Every variable MultiCred manages; unset first so keys of the previous
    # profile never leak into the next one.
    managed_vars: list[str]
    claude: ClaudeTarget
    api_keys: list[APIKeyExport] = field(default_factory=list)


def _header(env: ShellEnvironment) -> str:
    return f"# Generated by MultiCred. Do not edit. generation={env.generation}"


class SecretToolLookup:
    """Desktop: `secret-tool lookup service app.multicred.apikey account <UUID>`."""

    def __init__(self, secret_tool: str = SECRET_TOOL):
        self.secret_tool = secret_tool

    def posix(self, name: str, account: str) -> list[str]:
        tool, service, account = single_quoted(self.secret_tool), single_quoted(API_KEY_SERVICE), single_quoted(account)
        return [f'{name}="$({tool} lookup service {service} account {account} 2>/dev/null)" '
                f'&& [ -n "${name}" ] && export {name} || unset {name}']

    def fish(self, name: str, account: str) -> list[str]:
        tool, service = fish_single_quoted(self.secret_tool), fish_single_quoted(API_KEY_SERVICE)
        account = fish_single_quoted(account)
        # `set` keeps the command substitution's exit status in $status.
        return [f"set -l __multicred_value ({tool} lookup service {service} account {account} 2>/dev/null)",
                'if test $status -eq 0; and test -n "$__multicred_value"',
                f"    set -gx {name} $__multicred_value",
                "else",
                f"    set -q {name}; and set -e -g {name}",
                "end"]


class SecretFileReader:
    """Termux: reads `$HOME/.config/multicred/secrets/<UUID>` (written by FileSecretStore)
    with builtins only. A missing or empty file leaves the variable unset; a file without
    a trailing newline still counts (`read` fails at EOF but keeps what it read). The
    account must be a validated UUID: it is the only text that reaches the path, which is
    double-quoted so $HOME may contain spaces."""

    def _path(self, account: str) -> str:
        validate_account(account)
        return f'"{SECRETS_DIRECTORY_EXPRESSION}/{account}"'

    def posix(self, name: str, account: str) -> list[str]:
        path = self._path(account)
        # `[ -r ]` first so a missing file is no redirection error; `|| :` so neither a
        # missing file nor a last line without newline trips a user's `set -e`.
        return [f"{name}=''; [ -r {path} ] && {{ IFS= read -r {name} || :; }} < {path}; "
                f'[ -n "${name}" ] && export {name} || unset {name}']

    def fish(self, name: str, account: str) -> list[str]:
        path = self._path(account)
        # `read --line` stores the whole line without splitting it on spaces.
        return ["set -l __multicred_value ''",
                f"test -r {path}; and read -l --line __multicred_value < {path}",
                'if test -n "$__multicred_value"',
                f"    set -gx {name} $__multicred_value",
                "else",
                f"    set -q {name}; and set -e -g {name}",
                "end"]


def secret_reader_for(platform, secret_tool: str = SECRET_TOOL):
    """How env.sh/env.fish read secret values on `platform` (core/platform.py)."""
    from ..platform import SecretBackend
    if platform.secret_backend == SecretBackend.FILES:
        return SecretFileReader()
    return SecretToolLookup(secret_tool)


def render_posix(env: ShellEnvironment, secret_tool: str = SECRET_TOOL, reader=None) -> str:
    reader = reader or SecretToolLookup(secret_tool)
    lines = [_header(env)]
    if env.managed_vars:
        lines.append("unset " + " ".join(env.managed_vars))
    if env.claude.kind == "default":
        lines.append("unset CLAUDE_CONFIG_DIR")
    elif env.claude.kind == "directory":
        lines.append(f"export CLAUDE_CONFIG_DIR={single_quoted(env.claude.path)}")
    for key in env.api_keys:
        lines += reader.posix(key.env_var, key.secret_account)
    return "\n".join(lines) + "\n"


def render_fish(env: ShellEnvironment, secret_tool: str = SECRET_TOOL, reader=None) -> str:
    reader = reader or SecretToolLookup(secret_tool)
    lines = [_header(env)]
    for name in env.managed_vars:
        lines.append(f"set -q {name}; and set -e -g {name}")
    if env.claude.kind == "default":
        lines.append("set -q CLAUDE_CONFIG_DIR; and set -e -g CLAUDE_CONFIG_DIR")
    elif env.claude.kind == "directory":
        lines.append(f"set -gx CLAUDE_CONFIG_DIR {fish_single_quoted(env.claude.path)}")
    for key in env.api_keys:
        lines += reader.fish(key.env_var, key.secret_account)
    return "\n".join(lines) + "\n"
