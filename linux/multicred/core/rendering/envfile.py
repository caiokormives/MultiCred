"""env.sh (bash, zsh) and env.fish.

Only variable names (validated), canonical paths (quoted) and UUIDs reach these
files; secret values stay in the Secret Service and are read by `secret-tool`
when the shell sources the file.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from ..engine.types import ClaudeTarget
from ..quoting import fish_single_quoted, single_quoted
from ..secrets import API_KEY_SERVICE

SECRET_TOOL = "/usr/bin/secret-tool"


@dataclass(frozen=True)
class APIKeyExport:
    env_var: str
    secret_account: str


@dataclass
class ShellEnvironment:
    """The environment a profile wants in the user's shells."""

    generation: int
    # Every variable MultiCred manages; unset first so keys of the previous
    # profile never leak into the next one.
    managed_vars: list[str]
    claude: ClaudeTarget
    api_keys: list[APIKeyExport] = field(default_factory=list)


def _header(env: ShellEnvironment) -> str:
    return f"# Generated by MultiCred. Do not edit. generation={env.generation}"


def render_posix(env: ShellEnvironment, secret_tool: str = SECRET_TOOL) -> str:
    lines = [_header(env)]
    if env.managed_vars:
        lines.append("unset " + " ".join(env.managed_vars))
    if env.claude.kind == "default":
        lines.append("unset CLAUDE_CONFIG_DIR")
    elif env.claude.kind == "directory":
        lines.append(f"export CLAUDE_CONFIG_DIR={single_quoted(env.claude.path)}")
    tool, service = single_quoted(secret_tool), single_quoted(API_KEY_SERVICE)
    for key in env.api_keys:
        account, name = single_quoted(key.secret_account), key.env_var
        lines.append(f'{name}="$({tool} lookup service {service} account {account} 2>/dev/null)" '
                     f'&& [ -n "${name}" ] && export {name} || unset {name}')
    return "\n".join(lines) + "\n"


def render_fish(env: ShellEnvironment, secret_tool: str = SECRET_TOOL) -> str:
    lines = [_header(env)]
    for name in env.managed_vars:
        lines.append(f"set -q {name}; and set -e -g {name}")
    if env.claude.kind == "default":
        lines.append("set -q CLAUDE_CONFIG_DIR; and set -e -g CLAUDE_CONFIG_DIR")
    elif env.claude.kind == "directory":
        lines.append(f"set -gx CLAUDE_CONFIG_DIR {fish_single_quoted(env.claude.path)}")
    tool, service = fish_single_quoted(secret_tool), fish_single_quoted(API_KEY_SERVICE)
    for key in env.api_keys:
        account, name = fish_single_quoted(key.secret_account), key.env_var
        # `set` keeps the command substitution's exit status in $status.
        lines.append(f"set -l __multicred_value ({tool} lookup service {service} account {account} 2>/dev/null)")
        lines.append('if test $status -eq 0; and test -n "$__multicred_value"')
        lines.append(f"    set -gx {name} $__multicred_value")
        lines.append("else")
        lines.append(f"    set -q {name}; and set -e -g {name}")
        lines.append("end")
    return "\n".join(lines) + "\n"
