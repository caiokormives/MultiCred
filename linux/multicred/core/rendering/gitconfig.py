"""The file included at the end of the user's global git config.

An empty identity renders only the header, so the user's own user.* settings
apply (a profile without git does not switch git).
"""

from __future__ import annotations

import unicodedata

from ..quoting import single_quoted

HEADER = "# Generated by MultiCred. Do not edit: this file is rewritten on every profile switch.\n"


def render(identity, environment) -> str:
    if identity is None:
        return HEADER
    text = HEADER + "[user]\n"
    text += f"\tname = {quote(identity.name)}\n"
    text += f"\temail = {quote(identity.email)}\n"
    if identity.ssh_key_path is not None:
        path = environment.expand_tilde(identity.ssh_key_path)
        text += "[core]\n"
        text += f"\tsshCommand = {quote(f'ssh -i {single_quoted(path)} -o IdentitiesOnly=yes')}\n"
    return text


def quote(value: str) -> str:
    """git config quoting: double quotes, escape \\ and ".

    Validation rejects control characters before any switch; as a second line
    of defense they become spaces here, so a newline can never open a section.
    """
    flattened = "".join(" " if unicodedata.category(ch) == "Cc" else ch for ch in value)
    return '"' + flattened.replace("\\", "\\\\").replace('"', '\\"') + '"'
