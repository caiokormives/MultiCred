    def _claude_login_checks(self, context: VerifyContext) -> list[Check]:
        """Verifier.swift:130-155: the Claude account in use, or the folder's own login."""
        profile = context.profile
        if profile is None:
            return []
        title = "Claude Code · conta"
        folder = profile.claude_config_dir
        folder_name = self.environment.abbreviate(folder) if folder else "~/.claude (padrão)"
        account = context.config.claude_account(context.state.applied_claude_account_id)
        if account is not None:
            wording = self._secrets_wording
            is_login = account.kind == ClaudeAccountKind.LOGIN
            try:
                present = (uuid_text(account.id) in self.environment.claude_credentials.vault_keys() if is_login
                           else self.environment.secrets.contains_item(account.secret_account))
            except Exception as error:  # locked or unreachable keyring: cannot tell
                return [Check("claude.login", title, CheckStatus.WARNING, found=f"{wording.unavailable}: {error}",
                              hint=wording.unavailable_hint)]
            if present:
                email = f" · {account.email}" if account.email else ""
                stored = "login completo" if is_login else "token"
                return [Check("claude.login", title, CheckStatus.OK,
                              found=f"{account.nickname}{email} ({stored} {wording.located}), pasta {folder_name}")]
            command = (f"Entrar de novo na conta Claude {account.nickname} (claude auth login)." if is_login
                       else f"Gerar um novo token para a conta Claude {account.nickname} (claude setup-token).")
            return [Check("claude.login", title, CheckStatus.ERROR,
                          found=f"{account.nickname}: {'login' if is_login else 'token'} não está {wording.located}",
                          fix=Fix(f"login-claude:{uuid_text(account.id)}", command, kind=FixKind.LOGIN_CLAUDE,
                                  target=account.id))]

        status = self._folder_status(folder)
        kind = getattr(status, "kind", "unknown")
        if kind == "loggedIn":
            email = f" · {status.email}" if status.email else ""
            return [Check("claude.login", title, CheckStatus.OK, found=f"login da pasta {folder_name}{email}")]
        if kind == "loggedOut":
            command = f"Entrar no Claude Code na pasta {self.environment.abbreviate(folder) if folder else '~/.claude'} " \
                      "(claude auth login)."
            return [Check("claude.login", title, CheckStatus.ERROR, found=f"a pasta {folder_name} está sem login",
                          fix=Fix(f"login-claude-folder:{folder}", command, kind=FixKind.LOGIN_CLAUDE_FOLDER,
                                  target=folder))]
        return [Check("claude.login", title, CheckStatus.WARNING, found="status indisponível")]

    def _key_checks(self, context: VerifyContext) -> list[Check]:
        """Verifier.swift:158-171: one row per key of the profile; "Abrir chave…" when missing."""
        profile = context.profile
        checks = []
        wording = self._secrets_wording
        for key_id in (profile.api_key_ids if profile else []):
            key = context.config.api_key(key_id)
            if key is None:
                continue
            check_id, title = f"key.{uuid_text(key.id)}", f"{key.provider.display_name} · {key.env_var}"
            try:
                present = self.environment.secrets.contains_item(key.secret_account)
            except Exception as error:  # locked or unreachable Secret Service
                checks.append(Check(check_id, title, CheckStatus.WARNING, found=f"{wording.unavailable}: {error}",
                                    hint=wording.unavailable_hint))
                continue
            if present:
                checks.append(Check(check_id, title, CheckStatus.OK, found=f"{key.nickname} {wording.located}"))
            else:
                checks.append(Check(check_id, title, CheckStatus.ERROR, found=f"chave não está {wording.located}",
                                    fix=Fix(f"open-api-key:{uuid_text(key.id)}",
                                            f"Abrir a chave {key.nickname} para colar o valor de novo.",
                                            kind=FixKind.OPEN_API_KEY, target=key.id)))
        return checks

