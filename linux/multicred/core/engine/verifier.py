    def _shells_folder_check(self, config: Config, profile, state: ActiveState) -> Check:
        """env.sh (and env.fish) carry the profile's folder and the current generation
        (Mac `env.files`). Files only: shells are never spawned."""
        title = "Arquivos de ambiente do shell"
        folder = profile.claude_config_dir
        expected_text = f"{self._folder_text(folder)} · geração {state.generation}"
        files = [(self.paths.env_sh, "export CLAUDE_CONFIG_DIR=",
                  f"export CLAUDE_CONFIG_DIR={single_quoted(folder)}" if folder else "unset CLAUDE_CONFIG_DIR")]
        if ShellKind.FISH in config.settings.enabled_shells:
            files.append((self.paths.env_fish, "set -gx CLAUDE_CONFIG_DIR ",
                          f"set -gx CLAUDE_CONFIG_DIR {fish_single_quoted(folder)}" if folder
                          else "set -q CLAUDE_CONFIG_DIR; and set -e -g CLAUDE_CONFIG_DIR"))
        problems = []
        for path, prefix, wanted in files:
            text = _read_text(path)
            name = path.name
            if text is None:
                problems.append(f"{name} não existe")
                continue
            first = text.split("\n", 1)[0]
            generation = first[len(_ENV_HEADER):] if first.startswith(_ENV_HEADER) else "?"
            lines = text.split("\n")
            if wanted not in lines or generation != str(state.generation):
                raw = _env_line_value(text, prefix)
                current = None if raw is None else _unquote_single(raw.strip())
                problems.append(f"{name}: {self._folder_text(current)} · geração {generation}")
        generation_file = (_read_text(self.paths.generation) or "").strip()
        if not problems and generation_file != str(state.generation):
            problems.append(f"arquivo generation: {generation_file or 'ausente'}")
        if not problems:
            return Check("claude.shells", title, CheckStatus.OK, found=self._folder_text(folder),
                         section=CheckSection.INTEGRATION)
        return Check("claude.shells", title, CheckStatus.ERROR, found="; ".join(problems), expected=expected_text,
                     origin=self.environment.abbreviate(str(self.paths.env_sh)),
                     fix=self._reapply_fix(config, profile.name), section=CheckSection.INTEGRATION)

    def _legacy_checks(self, context: VerifyContext) -> list[Check]:
        """Verifier.swift:208-216: listed only while the old version is still active."""
        findings = LegacyMigration.findings(self.environment)
        if not findings:
            return []
        files = [self.environment.abbreviate(str(f.file)) for f in findings]
        first = findings[0]
        text = _read_text(first.file) or ""
        line = next((i for i, l in enumerate(text.split("\n"), start=1) if l in first.lines), None)
        return [Check("legacy", "Versão antiga (~/Perfis) ainda ativa", CheckStatus.ERROR,
                      found=", ".join(files), expected="nenhuma linha de ~/Perfis",
                      origin=files[0] + (f":{line}" if line else ""),
                      fix=self._install_fix(context.config, "Remover as linhas da versão antiga (~/Perfis) de "
                                                            f"{', '.join(files)} (com backup).", remove_legacy=True),
                      section=CheckSection.INTEGRATION)]

