_ENV_HEADER = "# Generated by MultiCred. Do not edit. generation="
UNREPRESENTABLE_FOLDER_HINT = ("O caminho tem $, \\, aspas ou crase: o environment.d não consegue guardá-lo e os apps "
                               "gráficos voltam à ~/.claude no próximo login. Renomeie a pasta.")


class CheckStatus(str, Enum):
    OK = "ok"
    PROBLEM = "problem"
    # Informative only (open Claude Code sessions): never counted, never a problem.
    INFO = "info"


@dataclass(frozen=True)
class Fix:
    # Checks whose repairs share a key are repaired by the same action
    # ("Corrigir tudo" runs it once).
    key: str
    # Shown to the user before anything runs ("Corrigir mostra o comando antes").
    command: str
    apply: Callable[[], object] = field(compare=False, repr=False)


@dataclass(frozen=True)
class Check:
    id: str
    title: str
    status: CheckStatus
    # What was found; for an ok row, the short description under the title.
    found: str | None = None
    expected: str | None = None
    # Where the found value comes from: `~/.gitconfig:14`.
    origin: str | None = None
    fix: Fix | None = None
    # Explanation or what to do by hand when there is no automatic fix.
    hint: str | None = None


@dataclass
class VerifyReport:
    checks: list[Check]
    checked_at: datetime
    profile_name: str | None = None
    # The state the report was computed against (a fix may have bumped it).
    state: ActiveState = field(default_factory=ActiveState)
    # Fixes that failed while producing this report, as user-readable text.
    errors: list[str] = field(default_factory=list)

    @property
    def system(self) -> list[Check]:
        return [c for c in self.checks if c.status != CheckStatus.INFO]

    @property
    def informative(self) -> list[Check]:
        return [c for c in self.checks if c.status == CheckStatus.INFO]

    @property
    def problems(self) -> list[Check]:
        return [c for c in self.checks if c.status == CheckStatus.PROBLEM]

    @property
    def fixable(self) -> list[Check]:
        return [c for c in self.problems if c.fix is not None]

    @property
    def ok_count(self) -> int:
        return sum(1 for c in self.system if c.status == CheckStatus.OK)

    @property
    def total(self) -> int:
        return len(self.system)

    @property
    def is_consistent(self) -> bool:
        return not self.problems


def _read_text(path: Path) -> str | None:
    """The file's text (a symlink is read at its destination), or None when missing/unreadable."""
    try:
        target = AtomicFileWriter.resolve_target(Path(path), follow_symlink=True)
        return target.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def _unquote_git_path(text: str) -> str:
    """git C-quotes origins with unusual characters: "file:\\"/a b\\303\\251\\"" style."""
    if len(text) >= 2 and text.startswith('"') and text.endswith('"'):
        raw = text[1:-1].encode("latin-1", "backslashreplace").decode("unicode_escape")
        return raw.encode("latin-1", "replace").decode("utf-8", "replace")
    return text


def _section_name(line: str) -> str | None:
    stripped = line.strip()
    if not stripped.startswith("["):
        return None
    inner = stripped[1:stripped.find("]")] if "]" in stripped else stripped[1:]
    return (inner.split()[0] if inner.split() else "").lower()


def _line_setting(path: str, key: str) -> int | None:
    """1-based line of the last `name = …` inside `[section]` of a git config file."""
    section, _, name = key.partition(".")
    text = _read_text(Path(path))
    if text is None:
        return None
    current, found = None, None
    pattern = re.compile(rf"^\s*{re.escape(name)}\s*=", re.IGNORECASE)
    for number, line in enumerate(text.split("\n"), start=1):
        header = _section_name(line)
        if header is not None:
            current = header
            continue
        if current == section.lower() and pattern.match(line):
            found = number
    return found


def _first_setting_after_block(text: str) -> int | None:
    """1-based line of the first non-comment line after the last MultiCred block."""
    lines = text.split("\n")
    stops = [i for i, line in enumerate(lines) if line.strip(" \t") == managed_block.END]
    if not stops:
        return None
    for index in range(stops[-1] + 1, len(lines)):
        trimmed = lines[index].strip(" \t")
        if trimmed and not trimmed.startswith(("#", ";")):
            return index + 1
    return None


def _env_line_value(text: str, prefix: str) -> str | None:
    for line in text.split("\n"):
        if line.startswith(prefix):
            return line[len(prefix):]
    return None


def _unquote_single(text: str) -> str:
    """Reverses quoting.single_quoted: 'it'\\''s' -> it's."""
    if len(text) >= 2 and text.startswith("'") and text.endswith("'"):
        return text[1:-1].replace("'\\''", "'")
    return text


class Verifier:
    def __init__(self, environment, tools, processes=None, engine: SwitchEngine | None = None, log=None):
        self.environment = environment
        self.tools = tools
        self.processes = processes
        self.paths = AppPaths(environment)
        # The app's engine, so a "reapply" fix shares its one-switch-at-a-time lock.
        self.engine = engine or SwitchEngine(environment, tools, log)
        self.log = log
        self._config: Config | None = None

    # MARK: public API

    def run(self, config: Config, state: ActiveState, deep: bool = False) -> VerifyReport:
        """Read-only. `deep` also asks gh whether the profile's token still works (network)."""
        self._config = config
        env = self.environment.base_process_environment(self.tools.search_directories())
        profile = config.profile(state.profile_id)
        checks = [self._git_check(config, profile, env)]
        if profile is not None:
            gh = self._github_check(config, profile, env, deep)
            if gh is not None:
                checks.append(gh)
            checks.append(self._shells_folder_check(config, profile, state))
            checks.append(self._session_check(profile, env))
        checks += self._integration_checks(config)
        if profile is not None:
            keys = self._keys_check(config, profile)
            if keys is not None:
                checks.append(keys)
        checks.append(self._legacy_check(config))
        if self.processes is not None:
            checks.append(self._sessions_info())
        return VerifyReport(checks, self.environment.clock(), profile.name if profile else None, state)

    def fix(self, check: Check, config: Config | None = None) -> VerifyReport:
        """Applies `check`'s fix if that check is still a problem now; returns a fresh report."""
        config = self._require(config)
        current = self._fresh(config)
        live = next((c for c in current.problems if c.id == check.id and c.fix is not None), None)
        if live is None:
            return current
        errors = self._apply(live)
        report = self._fresh(config)
        report.errors = errors
        return report

    def fix_all(self, report: VerifyReport | None = None, config: Config | None = None) -> VerifyReport:
        """Repairs every fixable problem, one repair at a time, re-checking in between so
        no repair runs for a check another repair already fixed. Failures are collected
        in the returned report's `errors`; the remaining repairs still run."""
        config = self._require(config)
        attempted: set[str] = set()
        errors: list[str] = []
        current = self._fresh(config)
        while True:
            pending = next((c for c in current.fixable if c.fix.key not in attempted), None)
            if pending is None:
                break
            attempted.add(pending.fix.key)
            errors += self._apply(pending)
            current = self._fresh(config)
        current.errors = errors
        return current

    # MARK: fixes

    def _require(self, config: Config | None) -> Config:
        config = config or self._config
        if config is None:
            raise ValueError("run() before fix(), or pass the configuration")
        return config

    def _fresh(self, config: Config) -> VerifyReport:
        state = StateStore(self.paths, self.environment.clock).load()
        return self.run(config, state, deep=False)

    def _apply(self, check: Check) -> list[str]:
        self._log("info", f"verify: fix {check.id} ({check.fix.key})")
        try:
            check.fix.apply()
        except Exception as error:  # every failure is shown to the user; the others still run
            self._log("error", f"verify: fix {check.id} failed: {error}")
            return [f"{check.title}: {error}"]
        return []

    def _install_fix(self, config: Config, command: str, remove_legacy: bool = False) -> Fix:
        shells = list(config.settings.enabled_shells)
        key = "install-legacy" if remove_legacy else "install"
        return Fix(key, command, lambda: Installer(self.environment).apply(
            InstallOptions(shells=shells, remove_legacy=remove_legacy)))

    def _reapply_fix(self, config: Config, profile_name: str) -> Fix:
        return Fix("reapply",
                   f"Reaplicar o perfil {profile_name}: reescreve o gitconfig incluído, a conta do gh, "
                   "CLAUDE_CONFIG_DIR (systemd --user e environment.d) e os arquivos de ambiente do shell.",
                   lambda: self.engine.reapply_active_profile(config))

    def _log(self, level: str, message: str) -> None:
        if self.log is not None:
            self.log.log(level, message)

    # MARK: checks

    def _git_value(self, git: str, key: str, env: dict[str, str]) -> tuple[str | None, str | None]:
        """Effective value as `git commit` sees it (with includes, D28) and the file it comes from."""
        request = CommandRequest(git, ["config", "--includes", "--show-origin", "--get", key], env,
                                 # Not inside any repository (some people version their home folder).
                                 cwd="/", timeout=10)
        try:
            result = self.environment.runner.run(request)
        except CommandError:
            return None, None
        if not result.succeeded:
            return None, None
        line = result.stdout.rstrip("\n")
        if "\t" not in line:
            return line, None
        origin, value = line.split("\t", 1)
        origin = _unquote_git_path(origin[5:] if origin.startswith("file:") else origin)
        return value, origin

    def _git_check(self, config: Config, profile, env) -> Check:
        global_file = Integrations.global_git_config(self.environment)
        global_name = self.environment.abbreviate(str(global_file))
        text = _read_text(global_file) or ""
        has_block = managed_block.contains(text)
        placement_ok = has_block and managed_block.is_last(text)
        identity = config.git_identity(profile.git_identity_id) if profile else None

        mismatches = []  # (label, expected, found, origin path)
        missing_git = False
        if identity is not None:
            git = self.tools.locate(Tool.GIT)
            if git is None:
                missing_git = True
            else:
                for key, label, expected in (("user.name", "Nome", identity.name),
                                             ("user.email", "E-mail", identity.email)):
                    value, origin = self._git_value(git, key, env)
                    if value != expected:
                        mismatches.append((key, label, expected, value, origin))

        if missing_git:
            return Check("git", "Identidade do git", CheckStatus.PROBLEM, found="git não encontrado",
                         hint="Instale o git (sudo apt install git) e verifique de novo.")
        if not mismatches and placement_ok:
            found = f"{identity.name} <{identity.email}>" if identity else global_name
            return Check("git", "Identidade do git" if identity else "Include do MultiCred no git",
                         CheckStatus.OK, found=found)

        # Where the wrong value comes from (file and line), or what follows the include.
        origin = hint = None
        ours = os.path.realpath(self.paths.gitconfig)
        from_ours = all(o is None or os.path.realpath(o) == ours for *_, o in mismatches)
        first_with_origin = next((m for m in mismatches if m[4] is not None), None)
        if first_with_origin is not None:
            key, _, _, _, path = first_with_origin
            line = _line_setting(path, key)
            origin = self.environment.abbreviate(path) + (f":{line}" if line else "")
            if os.path.realpath(path) == os.path.realpath(global_file) and has_block and not placement_ok:
                hint = "depois do include do MultiCred"
        elif has_block and not placement_ok:
            line = _first_setting_after_block(text)
            origin = global_name + (f":{line}" if line else "")

        if len(mismatches) == 2:
            title = "Identidade do git sobrescrita"
            expected = f"{mismatches[0][2]} <{mismatches[1][2]}>"
            found = f"{mismatches[0][3] or 'não definido'} <{mismatches[1][3] or 'não definido'}>"
        elif mismatches:
            _, label, expected, value, _ = mismatches[0]
            title = f"{label} do git sobrescrito"
            found = value or "não definido"
        elif has_block:
            title, expected, found = ("Include do MultiCred não é o último",
                                      f"include do MultiCred no fim de {global_name}", "há configurações depois do include")
        else:
            title, expected, found = ("Include do MultiCred removido",
                                      f"include do MultiCred no fim de {global_name}", "o include foi removido")

        if not placement_ok:
            verb = "Mover" if has_block else "Adicionar"
            fix = self._install_fix(config, f"{verb} o include do MultiCred para o fim de {global_name} (com backup).")
        elif from_ours:
            fix = self._reapply_fix(config, profile.name)
        else:
            fix = None
            hint = hint or "Remova a definição apontada na origem e verifique de novo."
        return Check("git", title, CheckStatus.PROBLEM, found=found, expected=expected, origin=origin, fix=fix,
                     hint=hint)

    def _github_check(self, config: Config, profile, env, deep: bool) -> Check | None:
        account = config.github_account(profile.github_account_id)
        if account is None:
            return None
        title = "Conta ativa do gh"
        gh = self.tools.locate(Tool.GH)
        if gh is None:
            return Check("gh", title, CheckStatus.PROBLEM, found="gh não encontrado",
                         hint="Instale o GitHub CLI (sudo apt install gh) e verifique de novo.")
        cli = GitHubCLI(self.environment.runner, gh, env)
        try:
            active = cli.active_login(account.host)
        except CommandError:
            active = None
        host, user = account.host, account.username
        found = f"{active} em {host}" if active else f"nenhuma conta ativa em {host}"
        active_ok = active is not None and active.lower() == user.lower()

        token_problem = None
        if deep:
            try:
                logins = cli.logins()
            except Exception:  # health is best effort; the active account was already checked
                logins = None
            if logins is not None:
                login = next((l for l in logins if l.host == host and l.login.lower() == user.lower()), None)
                if login is None:
                    token_problem = f"{user} não está no gh"
                elif not login.is_usable:
                    token_problem = f"o gh precisa de um novo login de {user}"

        if active_ok and token_problem is None:
            return Check("gh", title, CheckStatus.OK, found=found)
        if token_problem is not None:
            found = f"{found} · {token_problem}"
        fix = None
        if not active_ok:
            fix = Fix("gh", f"gh auth switch --hostname {quote_for_display(host)} --user {quote_for_display(user)}",
                      lambda: cli.switch_account(host, user))
        hint = "Entre de novo na conta do GitHub em Contas." if token_problem else None
        return Check("gh", title, CheckStatus.PROBLEM, found=found, expected=None if active_ok else user, fix=fix,
                     hint=hint)

    def _folder_text(self, folder: str | None) -> str:
        if folder is None:
            return "CLAUDE_CONFIG_DIR não definido (~/.claude)"
        return f"CLAUDE_CONFIG_DIR={self.environment.abbreviate(folder)}"

    def _shells_folder_check(self, config: Config, profile, state: ActiveState) -> Check:
        """env.sh (and env.fish) carry the profile's folder and the current generation.
        Files only: shells are never spawned."""
        title = "Pasta do Claude nos terminais"
        folder = profile.claude_config_dir
        expected_text = f"{self._folder_text(folder)} · geração {state.generation}"
        files = [(self.paths.env_sh, "export CLAUDE_CONFIG_DIR=",
                  f"export CLAUDE_CONFIG_DIR={single_quoted(folder)}" if folder else "unset CLAUDE_CONFIG_DIR")]
        if ShellKind.FISH in config.settings.enabled_shells:
            files.append((self.paths.env_fish, "set -gx CLAUDE_CONFIG_DIR ",
                          f"set -gx CLAUDE_CONFIG_DIR {fish_single_quoted(folder)}" if folder
                          else "set -q CLAUDE_CONFIG_DIR; and set -e -g CLAUDE_CONFIG_DIR"))
        problems = []
        for path, prefix, wanted in files:
            text = _read_text(path)
            name = path.name
            if text is None:
                problems.append(f"{name} não existe")
                continue
            first = text.split("\n", 1)[0]
            generation = first[len(_ENV_HEADER):] if first.startswith(_ENV_HEADER) else "?"
            lines = text.split("\n")
            if wanted not in lines or generation != str(state.generation):
                raw = _env_line_value(text, prefix)
                current = None if raw is None else _unquote_single(raw.strip())
                problems.append(f"{name}: {self._folder_text(current)} · geração {generation}")
        generation_file = (_read_text(self.paths.generation) or "").strip()
        if not problems and generation_file != str(state.generation):
            problems.append(f"arquivo generation: {generation_file or 'ausente'}")
        if not problems:
            return Check("claude.shells", title, CheckStatus.OK, found=self._folder_text(folder))
        return Check("claude.shells", title, CheckStatus.PROBLEM, found="; ".join(problems), expected=expected_text,
                     origin=self.environment.abbreviate(str(self.paths.env_sh)),
                     fix=self._reapply_fix(config, profile.name))

    def _session_check(self, profile, env) -> Check:
        title = "Pasta do Claude na sessão gráfica"
        folder = profile.claude_config_dir
        session = SessionEnvironment(self.environment, env)
        error = None
        try:
            manager = session.get(CLAUDE_VARIABLE)
        except Exception as failure:  # no user manager, systemctl missing…
            manager, error = None, str(failure)
        file = self.environment.home / ENVIRONMENT_D_FILE
        text = _read_text(file)
        file_value = None if text is None else _env_line_value(text, f"{CLAUDE_VARIABLE}=")
        wanted_file = folder if folder is not None and environment_d_line(CLAUDE_VARIABLE, folder) else None
        display = self.environment.abbreviate(folder) if folder else "~/.claude (padrão)"
        if folder is not None and not representable(folder):
            # No repair can help: systemd drops the variable at the next login.
            running = "erro" if error else ("ok" if manager == folder else "não definido")
            return Check("claude.session", title, CheckStatus.PROBLEM,
                         found=f"systemd --user: {running} · environment.d não guarda este caminho",
                         expected=display, hint=UNREPRESENTABLE_FOLDER_HINT)
        if error is None and manager == folder and file_value == wanted_file:
            return Check("claude.session", title, CheckStatus.OK, found=f"{display} em systemd --user e environment.d")

        def shown(value):
            return self.environment.abbreviate(value) if value else "não definido"

        manager_text = f"erro: {error}" if error else shown(manager)
        file_text = "sem o arquivo" if text is None else shown(file_value)
        found = f"systemd --user: {manager_text} · environment.d: {file_text}"
        file_name = self.environment.abbreviate(str(file))
        if folder is None:
            command = f"systemctl --user unset-environment {CLAUDE_VARIABLE} e apagar {file_name}"
        else:
            command = (f"systemctl --user set-environment {quote_for_display(f'{CLAUDE_VARIABLE}={folder}')} "
                       f"e gravar {file_name}")
        return Check("claude.session", title, CheckStatus.PROBLEM, found=found, expected=display,
                     origin=file_name if file_value != wanted_file else None,
                     fix=Fix("session", command, lambda: session.apply(CLAUDE_VARIABLE, folder)))

    def _integration_checks(self, config: Config) -> list[Check]:
        checks = []
        for shell in config.settings.enabled_shells:
            if shell == ShellKind.FISH:
                files = [Integrations.fish_conf_file(self.environment)]
            else:
                files = Integrations.rc_files(shell, self.environment)
            names = [self.environment.abbreviate(str(f)) for f in files]
            without_block = [n for f, n in zip(files, names) if not managed_block.contains(_read_text(f) or "")]
            hook = self.paths.hook(shell)
            hook_ok = _read_text(hook) == hooks.render(shell)
            title = f"{shell.value} integrado"
            if not without_block and hook_ok:
                checks.append(Check(f"shell.{shell.value}", title, CheckStatus.OK, found=", ".join(names)))
                continue
            problems = [f"{n} sem o bloco do MultiCred" for n in without_block]
            if not hook_ok:
                problems.append(f"hook ausente ou diferente ({self.environment.abbreviate(str(hook))})")
            joined = " e ".join(names)
            checks.append(Check(
                f"shell.{shell.value}", title, CheckStatus.PROBLEM, found="; ".join(problems),
                expected=f"bloco do MultiCred em {joined}",
                fix=self._install_fix(config, f"Reescrever o bloco do MultiCred no fim de {joined} e o hook do "
                                              f"{shell.value} (com backup).")))
        return checks

    def _keys_check(self, config: Config, profile) -> Check | None:
        keys = [k for k in (config.api_key(i) for i in profile.api_key_ids) if k is not None]
        if not keys:
            return None
        title = "Chaves no chaveiro"
        names = ", ".join(k.env_var for k in keys)
        try:
            missing = [k for k in keys if not self.environment.secrets.contains_item(k.secret_account)]
        except Exception as error:  # locked or unreachable Secret Service
            return Check("keys", title, CheckStatus.PROBLEM, found=f"chaveiro indisponível: {error}", expected=names,
                         hint="Desbloqueie o chaveiro e verifique de novo.")
        if not missing:
            return Check("keys", title, CheckStatus.OK, found=names)
        return Check("keys", title, CheckStatus.PROBLEM,
                     found="faltando: " + ", ".join(f"{k.env_var} ({k.nickname})" for k in missing),
                     expected=names, hint="Edite a conta em Contas e cole a chave de novo.")

    def _legacy_check(self, config: Config) -> Check:
        findings = LegacyMigration.findings(self.environment)
        if not findings:
            return Check("legacy", "Sem versão antiga (~/Perfis)", CheckStatus.OK)
        files = [self.environment.abbreviate(str(f.file)) for f in findings]
        first = findings[0]
        text = _read_text(first.file) or ""
        line = next((i for i, l in enumerate(text.split("\n"), start=1) if l in first.lines), None)
        return Check("legacy", "Versão antiga (~/Perfis) ainda ativa", CheckStatus.PROBLEM,
                     found=", ".join(files), expected="nenhuma linha de ~/Perfis",
                     origin=files[0] + (f":{line}" if line else ""),
                     fix=self._install_fix(config, "Remover as linhas da versão antiga (~/Perfis) de "
                                                   f"{', '.join(files)} (com backup).", remove_legacy=True))

    def _sessions_info(self) -> Check:
        try:
            count = self.processes.claude_code_session_count()
        except Exception:
            count = 0
        if count == 0:
            return Check("claude.sessions", "Nenhuma sessão do Claude Code aberta", CheckStatus.INFO)
        title = "1 sessão do Claude Code aberta" if count == 1 else f"{count} sessões do Claude Code abertas"
        return Check("claude.sessions", title, CheckStatus.INFO, found="continuam na conta anterior até reiniciar")
