"""Verificar e Corrigir (design 06; port of Engine/Verifier.swift, Linux checks).

Compares what the active profile expects with what git, gh, the shells, the
graphical session and the Secret Service really have. `run` only reads (git and
gh are asked offline; gh token health is network-bound and only checked with
`deep=True`). Each problem may carry a Fix: the command shown to the user before
anything runs, plus the callable that applies it, or (like the Mac's `loginClaude`,
`loginClaudeFolder`, `loginGitHub` and `setAPIKeySecret`) the page the user must go
to: a login or a key's editor. Those run nothing here; the screen opens the page.

    run ──► VerifyReport ──► fix(check) / fix_all(report) ──► fresh VerifyReport

Like `CheckItem` on the Mac, every check has a section (Ferramentas, Integração,
Sessões) and a status: ok, error (✗, a problem: the profile is not really in effect),
warning (!, worth a look but not an inconsistency) or info (never counted).

A fix is applied only to a check that is a problem in a fresh run, never to a
row of an old report that has meanwhile become ok.

The checks come from `Verifier.producers`, an ordered list of functions
(VerifyContext → list[Check]) chosen for the platform: without a graphical session
(Termux) there is no "pasta para apps" check (systemctl --user, environment.d), and
Termux gets a Claude Code check instead (core/claude/termux_support.py: versions from
2.1.113 on do not run on Android). Texts name where secrets really live (the
system keyring, or Termux's secret files) and Termux's `pkg`.
"""

