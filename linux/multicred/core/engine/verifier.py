    def _shell_checks(self, context: VerifyContext) -> list[Check]:
        """Verifier.swift:175-190: each enabled shell's rc files carry the block and its hook is current."""
        config = context.config
        checks = []
        for shell in config.settings.enabled_shells:
            if shell == ShellKind.FISH:
                files = [Integrations.fish_conf_file(self.environment)]
