"""env.sh / env.fish read back by real shells, with a fake secret-tool."""

import shutil
import subprocess
import uuid

from multicred.core.engine.types import ClaudeTarget
from multicred.core.rendering.envfile import SECRET_TOOL, APIKeyExport, ShellEnvironment, render_fish, render_posix
from tests.support import SafeTestCase

KNOWN = "6B1F4C1E-0D7A-4E0B-9A3E-3C1C2B0F9A11"

# Stands in for /usr/bin/secret-tool: answers only `lookup service app.multicred.apikey account <KNOWN>`.
FAKE_SECRET_TOOL = f"""#!/bin/sh
[ "$1" = lookup ] && [ "$2" = service ] && [ "$3" = app.multicred.apikey ] && [ "$4" = account ] && [ "$5" = {KNOWN} ] || exit 1
printf 'sk-test-value'
"""


class EnvFileRendererTests(SafeTestCase):
    def setUp(self):
        super().setUp()
        self.tool = self.make_executable("fake-secret-tool", FAKE_SECRET_TOOL)

    def shell_env(self, claude, keys):
        return ShellEnvironment(generation=7, managed_vars=["GEMINI_API_KEY", "OPENAI_API_KEY"], claude=claude,
                                api_keys=keys)

    def source_and_print(self, path, preset=""):
        script = f'{preset}\n. "$1"\nprintf \'%s|%s|%s\' "${{CLAUDE_CONFIG_DIR-unset}}" "${{OPENAI_API_KEY-unset}}" "${{GEMINI_API_KEY-unset}}"'
        return subprocess.run(["/bin/sh", "-c", script, "sh", str(path)], capture_output=True, text=True,
                              env={"HOME": str(self.home), "PATH": "/usr/bin:/bin"}).stdout

    def test_exports_directory_and_key_and_unsets_other_managed_vars(self):
        path = self.home / "env.sh"
        env = self.shell_env(ClaudeTarget.directory(f"{self.home}/.claude-x y'z"), [APIKeyExport("OPENAI_API_KEY", KNOWN)])
        path.write_text(render_posix(env, secret_tool=str(self.tool)))
        output = self.source_and_print(path, "export GEMINI_API_KEY=leaked-from-previous-profile")
        self.assertEqual(output, f"{self.home}/.claude-x y'z|sk-test-value|unset")

    def test_default_folder_unsets_variable_and_missing_key_stays_unset(self):
        path = self.home / "env.sh"
        env = self.shell_env(ClaudeTarget.default(), [APIKeyExport("OPENAI_API_KEY", str(uuid.uuid4()).upper())])
        path.write_text(render_posix(env, secret_tool=str(self.tool)))
        self.assertEqual(self.source_and_print(path, "export CLAUDE_CONFIG_DIR=/old"), "unset|unset|unset")

    def test_empty_secret_is_not_exported(self):
        empty = self.make_executable("empty-secret-tool", "#!/bin/sh\nexit 0\n")
        path = self.home / "env.sh"
        path.write_text(render_posix(self.shell_env(ClaudeTarget.unchanged(), [APIKeyExport("OPENAI_API_KEY", KNOWN)]),
                                     secret_tool=str(empty)))
        self.assertEqual(self.source_and_print(path), "unset|unset|unset")

    def test_unchanged_leaves_claude_variable_alone(self):
        path = self.home / "env.sh"
        path.write_text(render_posix(self.shell_env(ClaudeTarget.unchanged(), []), secret_tool=str(self.tool)))
        self.assertEqual(self.source_and_print(path, "export CLAUDE_CONFIG_DIR=/kept"), "/kept|unset|unset")

    def test_real_secret_tool_path_is_the_default(self):
        text = render_posix(self.shell_env(ClaudeTarget.unchanged(), [APIKeyExport("OPENAI_API_KEY", KNOWN)]))
        self.assertEqual(SECRET_TOOL, "/usr/bin/secret-tool")
        self.assertIn(f"'/usr/bin/secret-tool' lookup service 'app.multicred.apikey' account '{KNOWN}'", text)
        self.assertTrue(text.startswith("# Generated by MultiCred. Do not edit. generation=7\n"))

    def test_fish_rendering(self):
        text = render_fish(self.shell_env(ClaudeTarget.directory("/a b/it's"), [APIKeyExport("OPENAI_API_KEY", KNOWN)]))
        self.assertIn("set -gx CLAUDE_CONFIG_DIR '/a b/it\\'s'", text)
        self.assertIn("set -q OPENAI_API_KEY; and set -e -g OPENAI_API_KEY", text)
        self.assertIn("if test $status -eq 0; and test -n \"$__multicred_value\"\n    set -gx OPENAI_API_KEY $__multicred_value\nelse", text)

    def test_fish_file_with_real_fish_when_installed(self):
        fish = shutil.which("fish")
        if fish is None:
            self.skipTest("fish is not installed")
        path = self.home / "env.fish"
        env = self.shell_env(ClaudeTarget.directory("/a b"), [APIKeyExport("OPENAI_API_KEY", KNOWN)])
        path.write_text(render_fish(env, secret_tool=str(self.tool)))
        out = subprocess.run([fish, "--no-config", "-c", "set -gx GEMINI_API_KEY old; source $argv[1]; printf '%s|%s|%s' "
                              "$CLAUDE_CONFIG_DIR $OPENAI_API_KEY (set -q GEMINI_API_KEY; and echo set; or echo unset)",
                              str(path)], capture_output=True, text=True).stdout
        self.assertEqual(out, "/a b|sk-test-value|unset")

    def test_shell_metacharacters_never_execute(self):
        marker = self.home / "pwned"
        evil = f"/x/$(touch {marker})`touch {marker}`'; touch {marker}; '"
        path = self.home / "env.sh"
        path.write_text(render_posix(self.shell_env(ClaudeTarget.directory(evil), []), secret_tool=str(self.tool)))
        output = self.source_and_print(path)
        self.assertFalse(marker.exists())
        self.assertTrue(output.startswith(evil + "|"))
