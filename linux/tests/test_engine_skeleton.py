"""S-01: choosing a profile switches the git identity end to end."""

import json
import os
import subprocess
import tempfile
from pathlib import Path

from multicred.core import real_env
from multicred.core.engine.switch_engine import SwitchEngine
from multicred.core.engine.types import Busy, InvalidConfiguration, Preflight, StepFailed
from multicred.core.models import Config, GitIdentity, Profile, ProfileColor
from multicred.core.paths import AppPaths
from multicred.core.storage import ConfigRepository
from tests.support import FIXED_NOW, SafeTestCase


class FixedTools:
    """Tool locator for tests: nothing installed besides what the test says."""

    def __init__(self, found=None):
        self.found = found or {}

    def locate(self, tool):
        return self.found.get(tool)

    def search_directories(self):
        return ["/usr/bin", "/bin"]


def two_profiles():
    work = GitIdentity(nickname="NPU", name="Rafael Leivas", email="r@npu.com.br", color=ProfileColor.INDIGO)
    personal = GitIdentity(nickname="Pessoal", name="Rafa", email="rafa@example.com", color=ProfileColor.ORANGE)
    config = Config(git_identities=[work, personal], profiles=[
        Profile(name="Trabalho", color=ProfileColor.INDIGO, git_identity_id=work.id),
        Profile(name="Pessoal", color=ProfileColor.ORANGE, git_identity_id=personal.id),
        Profile(name="Sem git", color=ProfileColor.GRAPHITE),
    ])
    return config


class SwitchSkeletonTests(SafeTestCase):
    def setUp(self):
        super().setUp()
        from tests.test_engine import FakeSystem
        self.system = FakeSystem(self.runner)  # gh and systemctl --user
        self.paths = AppPaths(self.environment)
        self.engine = SwitchEngine(self.environment, FixedTools())
        self.config = two_profiles()

    def git_email(self):
        result = subprocess.run(["git", "config", "--file", str(self.paths.gitconfig), "--get", "user.email"],
                                env={"HOME": str(self.home), "PATH": "/usr/bin:/bin", "GIT_CONFIG_NOSYSTEM": "1"},
                                capture_output=True, text=True)
        return result.stdout.strip()

    def test_switch_writes_git_identity_state_and_bumps_generation(self):
        work = self.config.profiles[0]
        result = self.engine.switch_profile(work.id, self.config)
        self.assertEqual(self.git_email(), "r@npu.com.br")
        self.assertEqual(self.read(self.paths.generation), "1\n")
        state = json.loads(self.read(self.paths.state))
        self.assertEqual(state["profileId"], str(work.id).upper())
        self.assertEqual(result.state.generation, 1)
        self.assertEqual(result.state.activated_at, FIXED_NOW)
        self.assertEqual([k.value for k in result.applied_steps], ["git", "session", "envFiles", "state"])

        self.engine.switch_profile(self.config.profiles[1].id, self.config)
        self.assertEqual(self.git_email(), "rafa@example.com")
        self.assertEqual(self.read(self.paths.generation), "2\n")

    def test_profile_without_git_renders_only_the_header(self):
        self.engine.switch_profile(self.config.profiles[2].id, self.config)
        self.assertTrue(self.read(self.paths.gitconfig).startswith("# Generated by MultiCred"))
        self.assertEqual(self.git_email(), "")

    def test_invalid_configuration_is_rejected_before_anything(self):
        self.config.git_identities[0].email = "broken"
        with self.assertRaises(InvalidConfiguration):
            self.engine.switch_profile(self.config.profiles[0].id, self.config)
        self.assertFalse(self.paths.root.exists())

    def test_unknown_profile_is_a_preflight_failure(self):
        import uuid
        with self.assertRaises(Preflight) as raised:
            self.engine.switch_profile(uuid.uuid4(), self.config)
        self.assertEqual(raised.exception.failure.kind, "profileNotFound")
        self.assertFalse(self.paths.gitconfig.exists())

    def test_failure_at_commit_restores_the_previous_git_file(self):
        self.engine.switch_profile(self.config.profiles[0].id, self.config)
        before = self.read(self.paths.gitconfig)
        self.paths.generation.unlink()
        self.paths.generation.mkdir()  # the commit cannot write it any more
        with self.assertRaises(StepFailed) as raised:
            self.engine.switch_profile(self.config.profiles[1].id, self.config)
        self.assertEqual(raised.exception.step.value, "state")
        self.assertEqual(raised.exception.rollback.complete, True)
        self.assertEqual(self.read(self.paths.gitconfig), before)
        self.assertEqual(json.loads(self.read(self.paths.state))["generation"], 1)

    def test_a_second_switch_while_one_runs_is_busy(self):
        self.assertTrue(self.engine._lock.acquire(blocking=False))
        try:
            with self.assertRaises(Busy):
                self.engine.switch_profile(self.config.profiles[0].id, self.config)
        finally:
            self.engine._lock.release()

    def test_reapply_without_active_profile_does_nothing(self):
        self.assertIsNone(self.engine.reapply_active_profile(self.config))
        self.assertFalse(self.paths.state.exists())

    def test_reapply_writes_the_active_profile_again(self):
        self.engine.switch_profile(self.config.profiles[0].id, self.config)
        self.paths.gitconfig.unlink()
        result = self.engine.reapply_active_profile(self.config)
        self.assertEqual(result.state.generation, 2)
        self.assertEqual(self.git_email(), "r@npu.com.br")


class SandboxModeTests(SafeTestCase):
    """R-11: test mode never touches anything outside the sandbox."""

    def test_switch_in_test_mode_stays_inside_the_sandbox(self):
        sandbox = Path(tempfile.mkdtemp(prefix="multicred-sandbox-"))
        self.addCleanup(__import__("shutil").rmtree, sandbox, True)
        environment = real_env.make_sandbox(sandbox)
        self.assertEqual(environment.mode, "dryRun")
        self.assertEqual(environment.home, sandbox.resolve())

        real_root = real_env.real_home() / ".config/multicred"
        before = real_root.exists() and sorted(os.listdir(real_root))

        config = real_env.seed_sandbox(environment)
        ConfigRepository(environment).save(config)
        engine = SwitchEngine(environment, FixedTools())
        engine.switch_profile(config.profiles[0].id, config)

        self.assertTrue((sandbox / ".config/multicred/gitconfig").exists())
        after = real_root.exists() and sorted(os.listdir(real_root))
        self.assertEqual(before, after, "the real ~/.config/multicred must not change")
